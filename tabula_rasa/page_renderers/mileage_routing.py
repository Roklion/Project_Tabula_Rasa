from __future__ import annotations

from collections.abc import Callable, Mapping
from datetime import date
import math
from typing import TYPE_CHECKING, Any

import streamlit as st

from tabula_rasa.address_autocomplete import AddressSelection
from tabula_rasa.maps_routing import GoogleRoutesError
from tabula_rasa.storage import GoogleSheetsStorage

if TYPE_CHECKING:
    from tabula_rasa.page_renderers.mileage import MileageContext

class PartialRouteError(ValueError):
    """Outbound route succeeded but the reversed route needs another attempt."""

    def __init__(self, outbound: float, message: str) -> None:
        super().__init__(message)
        self.outbound = outbound


class RouteValidationError(ValueError):
    """A safe, user-facing validation message generated by the UI."""


def _route_key(context: MileageContext, workflow: str) -> str:
    return f"mileage_route_{context.profile_key}_{workflow}"


def _selection_fingerprint(
    start: AddressSelection, destination: AddressSelection
) -> tuple[str, str, int, int]:
    return (
        start.display_text,
        destination.display_text,
        start.version,
        destination.version,
    )


def _route_ready(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float] | None,
) -> bool:
    return bool(
        route_mileage
        and start.place_id
        and destination.place_id
        and start.place_id != destination.place_id
    )


def _route_disabled_reason(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float] | None,
    autocomplete_available: bool = True,
) -> str:
    """Explain why the explicit route action is currently unavailable."""
    if route_mileage is None:
        return (
            "Google Maps routing is not configured. Enter mileage manually "
            "or configure the Maps secrets."
        )
    if not autocomplete_available:
        return (
            "Google address suggestions are unavailable. Enter mileage manually "
            "or configure a browser Maps key."
        )
    if not start.place_id or not destination.place_id:
        return (
            "Choose a Google suggestion for both endpoints to enable mileage "
            "calculation. Manual entries can still be saved with entered miles."
        )
    if start.place_id == destination.place_id:
        return (
            "Choose different Google places for the starting location and destination."
        )
    return "Mileage calculation is unavailable. Enter miles manually or try again."


def _autocomplete_available(*keys: str) -> bool:
    """Return whether no address component has reported provider failure."""
    for key in keys:
        state = st.session_state.get(key)
        if isinstance(state, Mapping) and state.get("failed") is True:
            return False
    return True


def _route_state_is_current(
    route_state: object, fingerprint: tuple[object, ...]
) -> bool:
    """Accept calculated provenance only for the currently selected inputs."""
    return (
        isinstance(route_state, Mapping)
        and route_state.get("fingerprint") == fingerprint
    )


def _route_state_has_current_endpoints(
    route_state: object, endpoint_fingerprint: tuple[str, str, int, int]
) -> bool:
    """Check route endpoints without treating round-trip mode as an address."""
    if not isinstance(route_state, Mapping):
        return False
    route_fingerprint = route_state.get("fingerprint")
    return (
        isinstance(route_fingerprint, tuple)
        and route_fingerprint[: len(endpoint_fingerprint)] == endpoint_fingerprint
    )


def _needs_google_maps_attribution(
    start: AddressSelection,
    destination: AddressSelection,
    route_state: object,
    fingerprint: tuple[object, ...],
) -> bool:
    """Identify current-session Google content without persisting provenance."""
    return bool(
        start.place_id
        or destination.place_id
        or _route_state_is_current(route_state, fingerprint)
    )


def _apply_pending_route_mileage(
    pending: object,
    *,
    fingerprint: tuple[object, ...],
    round_trip: bool,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Populate editable mileage widgets after an explicit route calculation."""
    if not isinstance(pending, Mapping):
        return
    if pending.get("fingerprint") != fingerprint:
        return
    outbound = pending.get("outbound")
    if isinstance(outbound, (int, float)) and math.isfinite(float(outbound)):
        st.session_state[miles_key] = float(outbound)
        st.session_state[f"{miles_key}__calculated"] = float(outbound)
    if round_trip and return_miles_key:
        returned = pending.get("return")
        if isinstance(returned, (int, float)) and math.isfinite(float(returned)):
            st.session_state[return_miles_key] = float(returned)
            st.session_state[f"{return_miles_key}__calculated"] = float(returned)


def _edit_route_warning_visible(
    address_changed: bool,
    route_changed: bool,
    route_state: object,
    fingerprint: tuple[object, ...],
    *,
    recorded_address_changed: bool = False,
) -> bool:
    """Show an edit warning until a route is recalculated for new addresses."""
    return (
        route_changed
        or recorded_address_changed
        or (address_changed and not _route_state_is_current(route_state, fingerprint))
    )


def _discard_modified_calculated_mileage_markers(
    *,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Forget calculated provenance after a user edits a mileage widget."""
    for state_key in (miles_key, return_miles_key):
        if not state_key:
            continue
        marker_key = f"{state_key}__calculated"
        calculated = st.session_state.get(marker_key)
        if calculated is not None and st.session_state.get(state_key) != calculated:
            st.session_state.pop(marker_key, None)


def _set_widget_default(key: str, value: float) -> None:
    """Initialize a keyed numeric widget without also passing a default."""
    if key not in st.session_state:
        st.session_state[key] = value


def _clear_unchanged_calculated_mileage(
    route_state: object,
    *,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Clear untouched calculated values when their route becomes stale."""
    if not isinstance(route_state, Mapping):
        return
    for state_key, route_key in (
        (miles_key, "outbound"),
        (return_miles_key, "return"),
    ):
        if not state_key:
            continue
        marker_key = f"{state_key}__calculated"
        calculated = st.session_state.get(marker_key, route_state.get(route_key))
        if (
            isinstance(calculated, (int, float))
            and math.isfinite(float(calculated))
            and st.session_state.get(state_key) == float(calculated)
        ):
            st.session_state.pop(state_key, None)
            st.session_state.pop(marker_key, None)
        elif marker_key in st.session_state:
            st.session_state.pop(marker_key, None)


def _same_selected_place(
    start: AddressSelection, destination: AddressSelection
) -> bool:
    """Identify an invalid Google route without rejecting manual loop trips."""
    return bool(
        start.place_id
        and destination.place_id
        and start.place_id == destination.place_id
    )


def _address_text_changed(
    start: AddressSelection,
    destination: AddressSelection,
    original_start: str,
    original_destination: str,
) -> bool:
    """Identify an edit-form address change before a new route is calculated."""
    return (
        start.version > 0 and start.display_text.strip() != original_start.strip()
    ) or (
        destination.version > 0
        and destination.display_text.strip() != original_destination.strip()
    )


def _calculate_routes(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float],
    *,
    round_trip: bool,
    known_outbound: float | None = None,
) -> tuple[float, float | None]:
    """Call the injected routing function only for explicit user actions."""
    if not start.place_id or not destination.place_id:
        raise RouteValidationError(
            "Choose both addresses from Google suggestions first."
        )
    if start.place_id == destination.place_id:
        raise RouteValidationError(
            "Starting location and destination must be different."
        )
    outbound_result = (
        route_mileage(start.place_id, destination.place_id)
        if known_outbound is None
        else known_outbound
    )
    outbound = round(
        float(getattr(outbound_result, "suggested_miles", outbound_result)), 1
    )
    if not math.isfinite(outbound) or outbound <= 0:
        raise RouteValidationError("Google returned no usable mileage for this route.")
    if not round_trip:
        return outbound, None
    try:
        returned_result = route_mileage(destination.place_id, start.place_id)
        returned = round(
            float(getattr(returned_result, "suggested_miles", returned_result)), 1
        )
        if not math.isfinite(returned) or returned <= 0:
            raise RouteValidationError(
                "Google returned no usable mileage for the return route."
            )
    except Exception as error:
        raise PartialRouteError(
            outbound,
            "Outbound mileage was calculated, but the return route failed. "
            "Enter return miles manually or try Calculate mileage again.",
        ) from error
    return outbound, returned


def _save_round_trip(
    storage: GoogleSheetsStorage,
    *,
    trip_date: date,
    miles: float,
    return_miles: float,
    vehicle: str,
    start_location: str,
    destination: str,
    business_purpose: str,
    notes: str,
    tag_ids: list[str] | tuple[str, ...] = (),
    new_tag_name: str = "",
) -> Any:
    """Persist two legs with their independently editable distances."""
    kwargs = {
        "trip_date": trip_date,
        "miles": miles,
        "return_miles": return_miles,
        "vehicle": vehicle,
        "start_location": start_location,
        "destination": destination,
        "business_purpose": business_purpose,
        "notes": notes,
        "tag_ids": list(tag_ids),
        "new_tag_name": new_tag_name,
    }
    return storage.create_mileage_round_trip(**kwargs)


def _safe_route_error(error: Exception) -> str:
    if isinstance(error, GoogleRoutesError):
        return str(error)
    if isinstance(error, RouteValidationError):
        return str(error)
    return "Could not calculate mileage. Check the locations and try again."
