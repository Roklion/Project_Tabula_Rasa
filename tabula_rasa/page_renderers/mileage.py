"""Mileage page rendering and its explicit page context."""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from datetime import date
import math
from typing import Any

import pandas as pd
import streamlit as st

from tabula_rasa.address_autocomplete import (
    AddressSelection,
    address_autocomplete,
    render_google_maps_attribution,
)
from tabula_rasa.maps_routing import GoogleRoutesError
from tabula_rasa.presentation import render_global_footer, render_page_header
from tabula_rasa.storage import GoogleSheetsStorage, StorageError


@dataclass(frozen=True)
class MileageContext:
    """Dependencies supplied by the application shell for one profile."""

    profile_key: str
    storage: GoogleSheetsStorage
    confirmed_write: Callable[..., None]
    report_storage_error: Callable[[StorageError], None]
    reset_widget_state_if_requested: Callable[..., None]
    schedule_widget_reset: Callable[[str], None]
    maps_api_key: str | None = None
    route_mileage: Callable[[str, str], float] | None = None
    autocomplete_region_code: str | None = None


class PartialRouteError(ValueError):
    """Outbound route succeeded but the reversed route needs another attempt."""

    def __init__(self, outbound: float, message: str) -> None:
        super().__init__(message)
        self.outbound = outbound


class RouteValidationError(ValueError):
    """A safe, user-facing validation message generated by the UI."""


def _route_key(context: MileageContext, workflow: str) -> str:
    return f"mileage_route_{context.profile_key}_{workflow}"


def _selection_fingerprint(
    start: AddressSelection, destination: AddressSelection
) -> tuple[str, str, int, int]:
    return (
        start.display_text,
        destination.display_text,
        start.version,
        destination.version,
    )


def _route_ready(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float] | None,
) -> bool:
    return bool(
        route_mileage
        and start.place_id
        and destination.place_id
        and start.place_id != destination.place_id
    )


def _route_disabled_reason(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float] | None,
    autocomplete_available: bool = True,
) -> str:
    """Explain why the explicit route action is currently unavailable."""
    if route_mileage is None:
        return (
            "Google Maps routing is not configured. Enter mileage manually "
            "or configure the Maps secrets."
        )
    if not autocomplete_available:
        return (
            "Google address suggestions are unavailable. Enter mileage manually "
            "or configure a browser Maps key."
        )
    if not start.place_id or not destination.place_id:
        return (
            "Choose a Google suggestion for both endpoints to enable mileage "
            "calculation. Manual entries can still be saved with entered miles."
        )
    if start.place_id == destination.place_id:
        return "Choose different Google places for the starting location and destination."
    return "Mileage calculation is unavailable. Enter miles manually or try again."


def _autocomplete_available(*keys: str) -> bool:
    """Return whether no address component has reported provider failure."""
    for key in keys:
        state = st.session_state.get(key)
        if isinstance(state, Mapping) and state.get("failed") is True:
            return False
    return True


def _route_state_is_current(
    route_state: object, fingerprint: tuple[object, ...]
) -> bool:
    """Accept calculated provenance only for the currently selected inputs."""
    return (
        isinstance(route_state, Mapping)
        and route_state.get("fingerprint") == fingerprint
    )


def _needs_google_maps_attribution(
    start: AddressSelection,
    destination: AddressSelection,
    route_state: object,
    fingerprint: tuple[object, ...],
) -> bool:
    """Identify current-session Google content without persisting provenance."""
    return bool(
        start.place_id
        or destination.place_id
        or _route_state_is_current(route_state, fingerprint)
    )


def _ledger_location_text(
    selection: AddressSelection,
    *,
    label: str,
    key: str,
    existing_value: str = "",
    always_render: bool = False,
) -> str:
    """Return manual ledger text without persisting Google display content."""
    if not selection.place_id and not always_render:
        return selection.display_text
    if always_render:
        st.caption(
            "Enter the location text to record in the ledger. Google text is "
            "used only for route lookup."
        )
    elif selection.place_id:
        st.caption(
            "Google text is used only for route lookup. Enter the location text "
            "you want to record in the ledger."
        )
    version_key = f"{key}__autocomplete_version"
    if selection.place_id and st.session_state.get(version_key) != selection.version:
        st.session_state[key] = selection.display_text
        st.session_state[version_key] = selection.version
    elif key not in st.session_state:
        st.session_state[key] = existing_value or selection.display_text
    text = st.text_input(
        f"{label} (recorded text)",
        key=key,
        help="This text is saved to the Mileage ledger when you save the trip.",
    )
    return text


def _edit_address_initial_value(
    existing_value: object, maps_api_key: str | None
) -> str:
    """Keep edit lookups empty only when a separate Maps control exists."""
    return "" if maps_api_key else str(existing_value or "")


def _apply_pending_route_mileage(
    pending: object,
    *,
    fingerprint: tuple[object, ...],
    round_trip: bool,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Populate editable mileage widgets after an explicit route calculation."""
    if not isinstance(pending, Mapping):
        return
    if pending.get("fingerprint") != fingerprint:
        return
    outbound = pending.get("outbound")
    if isinstance(outbound, (int, float)) and math.isfinite(float(outbound)):
        st.session_state[miles_key] = float(outbound)
        st.session_state[f"{miles_key}__calculated"] = float(outbound)
    if round_trip and return_miles_key:
        returned = pending.get("return")
        if isinstance(returned, (int, float)) and math.isfinite(float(returned)):
            st.session_state[return_miles_key] = float(returned)
            st.session_state[f"{return_miles_key}__calculated"] = float(returned)


def _edit_route_warning_visible(
    address_changed: bool,
    route_changed: bool,
    route_state: object,
    fingerprint: tuple[object, ...],
    *,
    recorded_address_changed: bool = False,
) -> bool:
    """Show an edit warning until a route is recalculated for new addresses."""
    return (
        route_changed
        or recorded_address_changed
        or (
            address_changed
            and not _route_state_is_current(route_state, fingerprint)
        )
    )


def _recorded_address_changed(
    edited_value: str,
    saved_value: object,
    selection: AddressSelection,
) -> bool:
    """Ignore recorded text that was just populated from a Maps selection."""
    return edited_value.strip() != str(saved_value or "").strip() and not (
        selection.place_id
        and edited_value.strip() == selection.display_text.strip()
    )


def _discard_modified_calculated_mileage_markers(
    *,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Forget calculated provenance after a user edits a mileage widget."""
    for state_key in (miles_key, return_miles_key):
        if not state_key:
            continue
        marker_key = f"{state_key}__calculated"
        calculated = st.session_state.get(marker_key)
        if calculated is not None and st.session_state.get(state_key) != calculated:
            st.session_state.pop(marker_key, None)


def _clear_unchanged_calculated_mileage(
    route_state: object,
    *,
    miles_key: str,
    return_miles_key: str | None = None,
) -> None:
    """Clear untouched calculated values when their route becomes stale."""
    if not isinstance(route_state, Mapping):
        return
    for state_key, route_key in (
        (miles_key, "outbound"),
        (return_miles_key, "return"),
    ):
        if not state_key:
            continue
        marker_key = f"{state_key}__calculated"
        calculated = st.session_state.get(marker_key, route_state.get(route_key))
        if (
            isinstance(calculated, (int, float))
            and math.isfinite(float(calculated))
            and st.session_state.get(state_key) == float(calculated)
        ):
            st.session_state.pop(state_key, None)
            st.session_state.pop(marker_key, None)
        elif marker_key in st.session_state:
            st.session_state.pop(marker_key, None)


def _same_selected_place(
    start: AddressSelection, destination: AddressSelection
) -> bool:
    """Identify an invalid Google route without rejecting manual loop trips."""
    return bool(
        start.place_id
        and destination.place_id
        and start.place_id == destination.place_id
    )


def _address_text_changed(
    start: AddressSelection,
    destination: AddressSelection,
    original_start: str,
    original_destination: str,
) -> bool:
    """Identify an edit-form address change before a new route is calculated."""
    return (
        (
            start.version > 0
            and start.display_text.strip() != original_start.strip()
        )
        or (
            destination.version > 0
            and destination.display_text.strip() != original_destination.strip()
        )
    )


def _calculate_routes(
    start: AddressSelection,
    destination: AddressSelection,
    route_mileage: Callable[[str, str], float],
    *,
    round_trip: bool,
    known_outbound: float | None = None,
) -> tuple[float, float | None]:
    """Call the injected routing function only for explicit user actions."""
    if not start.place_id or not destination.place_id:
        raise RouteValidationError(
            "Choose both addresses from Google suggestions first."
        )
    if start.place_id == destination.place_id:
        raise RouteValidationError(
            "Starting location and destination must be different."
        )
    outbound_result = (
        route_mileage(start.place_id, destination.place_id)
        if known_outbound is None
        else known_outbound
    )
    outbound = round(
        float(getattr(outbound_result, "suggested_miles", outbound_result)), 1
    )
    if not math.isfinite(outbound) or outbound <= 0:
        raise RouteValidationError(
            "Google returned no usable mileage for this route."
        )
    if not round_trip:
        return outbound, None
    try:
        returned_result = route_mileage(destination.place_id, start.place_id)
        returned = round(
            float(getattr(returned_result, "suggested_miles", returned_result)), 1
        )
        if not math.isfinite(returned) or returned <= 0:
            raise RouteValidationError(
                "Google returned no usable mileage for the return route."
            )
    except Exception as error:
        raise PartialRouteError(
            outbound,
            "Outbound mileage was calculated, but the return route failed. "
            "Enter return miles manually or try Calculate mileage again.",
        ) from error
    return outbound, returned


def _save_round_trip(
    storage: GoogleSheetsStorage,
    *,
    trip_date: date,
    miles: float,
    return_miles: float,
    vehicle: str,
    start_location: str,
    destination: str,
    business_purpose: str,
    notes: str,
) -> Any:
    """Persist two legs with their independently editable distances."""
    kwargs = {
        "trip_date": trip_date,
        "miles": miles,
        "return_miles": return_miles,
        "vehicle": vehicle,
        "start_location": start_location,
        "destination": destination,
        "business_purpose": business_purpose,
        "notes": notes,
    }
    return storage.create_mileage_round_trip(**kwargs)


def _safe_route_error(error: Exception) -> str:
    if isinstance(error, GoogleRoutesError):
        return str(error)
    if isinstance(error, RouteValidationError):
        return str(error)
    return "Could not calculate mileage. Check the locations and try again."


def mileage_frame(trips: list[dict]) -> pd.DataFrame:
    """Return the stable, user-facing eight-column mileage table."""
    return pd.DataFrame(
        [
            {
                "ID": trip["id"],
                "Date": trip["trip_date"],
                "Miles": float(trip["miles"]),
                "From": trip.get("start_location", ""),
                "Destination": trip.get("destination", ""),
                "Business purpose": trip.get("business_purpose", ""),
                "Vehicle": trip.get("vehicle", ""),
                "Notes": trip.get("notes", ""),
            }
            for trip in trips
        ],
        columns=[
            "ID",
            "Date",
            "Miles",
            "From",
            "Destination",
            "Business purpose",
            "Vehicle",
            "Notes",
        ],
    )


def render_mileage(context: MileageContext) -> None:
    """Render mileage entry, filtering, editing, export, and deletion."""
    render_page_header(
        "Mileage",
        "Keep a dated business-mileage log with the route, purpose, and vehicle.",
    )
    tab_add, tab_log = st.tabs(["Add trip", "View & edit mileage log"])
    page_footer = st.empty()

    with tab_add:
        mileage_form_keys = (
            "add_mileage_trip_date",
            "add_mileage_miles",
            "add_mileage_vehicle",
            "add_mileage_start",
            "add_mileage_destination",
            "add_mileage_round_trip",
            "add_mileage_purpose",
            "add_mileage_notes",
            "add_mileage_return_miles",
            "add_mileage_start__selection",
            "add_mileage_destination__selection",
            "add_mileage_recorded_start",
            "add_mileage_recorded_destination",
            "add_mileage_recorded_start__autocomplete_version",
            "add_mileage_recorded_destination__autocomplete_version",
            _route_key(context, "add"),
            f"{_route_key(context, 'add')}__pending_miles",
            "add_mileage_miles__calculated",
            "add_mileage_return_miles__calculated",
        )
        context.reset_widget_state_if_requested(
            "reset_add_mileage_form",
            keys=mileage_form_keys,
        )

        st.subheader("Add trip")
        # Address widgets stay outside the form so browser selection events
        # can update their Place IDs without submitting the form.
        c1, c2 = st.columns(2, gap="small")
        start_selection = c1.empty()
        destination_selection = c2.empty()
        with start_selection:
            start = address_autocomplete(
                "Starting location",
                key="add_mileage_start",
                api_key=context.maps_api_key,
                region_code=context.autocomplete_region_code,
            )
        with destination_selection:
            destination_value = address_autocomplete(
                "Destination",
                key="add_mileage_destination",
                api_key=context.maps_api_key,
                region_code=context.autocomplete_region_code,
            )

        add_route_key = _route_key(context, "add")
        route_state = st.session_state.get(add_route_key)
        round_trip = bool(
            st.session_state.get("add_mileage_round_trip", False)
        )
        fingerprint = (*_selection_fingerprint(start, destination_value), round_trip)
        pending_mileage_key = f"{add_route_key}__pending_miles"
        _apply_pending_route_mileage(
            st.session_state.pop(pending_mileage_key, None),
            fingerprint=fingerprint,
            round_trip=round_trip,
            miles_key="add_mileage_miles",
            return_miles_key="add_mileage_return_miles",
        )
        _discard_modified_calculated_mileage_markers(
            miles_key="add_mileage_miles",
            return_miles_key="add_mileage_return_miles",
        )
        address_changed = False
        if route_state and route_state.get("fingerprint") != fingerprint:
            # A changed address invalidates a previously calculated route.
            _clear_unchanged_calculated_mileage(
                route_state,
                miles_key="add_mileage_miles",
                return_miles_key="add_mileage_return_miles",
            )
            st.session_state.pop(add_route_key, None)
            route_state = None
            address_changed = True
        route_error = st.empty()
        route_ready = _route_ready(
            start, destination_value, context.route_mileage
        )
        route_disabled_reason = _route_disabled_reason(
            start,
            destination_value,
            context.route_mileage,
            autocomplete_available=(
                context.maps_api_key is not None
                and _autocomplete_available(
                    "add_mileage_start", "add_mileage_destination"
                )
            ),
        )
        calculate_requested = st.button(
            "Recalculate mileage" if route_state else "Calculate mileage",
            disabled=not route_ready,
            help=route_disabled_reason if not route_ready else None,
        )
        if not route_ready and context.route_mileage is not None:
            st.caption(route_disabled_reason)

        round_trip = st.checkbox(
            "Round trip",
            help=(
                "Creates an outbound entry and a second entry with the "
                "starting and ending locations reversed. Outbound and return "
                "mileage can be reviewed independently."
            ),
            key="add_mileage_round_trip",
        )
        if address_changed:
            if route_ready:
                st.warning(
                    "The selected addresses changed, so any mileage left in "
                    "the boxes may not match the current route. Calculate "
                    "mileage again to refresh it before saving."
                )
            else:
                st.warning(
                    "The selected addresses changed, so any mileage left in "
                    "the boxes may not match the current route. Review or "
                    "enter mileage manually before saving."
                )
        if route_state and route_state.get("partial"):
            st.warning(
                "Outbound mileage is ready. Enter return miles manually or "
                "retry the return route."
            )
        recorded_columns = st.columns(2, gap="small")
        with recorded_columns[0]:
            recorded_start = _ledger_location_text(
                start,
                label="Starting location",
                key="add_mileage_recorded_start",
                always_render=bool(context.maps_api_key),
            )
        with recorded_columns[1]:
            recorded_destination = _ledger_location_text(
                destination_value,
                label="Destination",
                key="add_mileage_recorded_destination",
                always_render=bool(context.maps_api_key),
            )

        # Keep draft widgets in page state so address-component reruns cannot
        # discard unsubmitted edits.
        with st.container():
            c1, c2 = st.columns(2, gap="small")
            trip_date = c1.date_input(
                "Trip date", date.today(), key="add_mileage_trip_date"
            )
            vehicle = c2.text_input(
                "Vehicle (optional)",
                help="For example: 2022 Honda Civic or Company van.",
                key="add_mileage_vehicle",
            )
            c1, c2 = st.columns(2, gap="small")
            miles = c1.number_input(
                "Business miles", min_value=0.0, step=0.1, value=0.0,
                format="%.1f",
                key="add_mileage_miles",
            )
            return_miles = miles
            if round_trip:
                return_miles = st.number_input(
                    "Return business miles",
                    min_value=0.0,
                    step=0.1,
                    value=float(miles),
                    format="%.1f",
                    key="add_mileage_return_miles",
                    help="The return route is editable independently.",
                )
            if _needs_google_maps_attribution(
                start, destination_value, route_state, fingerprint
            ):
                render_google_maps_attribution()
            business_purpose = st.text_input(
                "Business purpose", key="add_mileage_purpose"
            )
            notes = st.text_area("Notes (optional)", key="add_mileage_notes")
            save_error = st.empty()
            submitted = st.button(
                "Save mileage trip", type="primary", width="stretch"
            )
            if calculate_requested and context.route_mileage is not None:
                with st.spinner("Calculating mileage…"):
                    try:
                        known_outbound = (
                            route_state.get("outbound")
                            if route_state and route_state.get("partial")
                            else None
                        )
                        preserve_manual_outbound = bool(
                            round_trip
                            and route_state
                            and route_state.get("partial")
                            and st.session_state.get(
                                "add_mileage_miles__calculated"
                            )
                            is None
                        )
                        outbound, returned = _calculate_routes(
                            start,
                            destination_value,
                            context.route_mileage,
                            round_trip=round_trip,
                            known_outbound=known_outbound,
                        )
                        st.session_state[add_route_key] = {
                            "fingerprint": fingerprint,
                            "outbound": outbound,
                            "return": returned,
                        }
                        st.session_state[pending_mileage_key] = {
                            "fingerprint": fingerprint,
                            "outbound": (
                                None if preserve_manual_outbound else outbound
                            ),
                            "return": returned,
                        }
                        st.rerun()
                    except PartialRouteError as error:
                        st.session_state[add_route_key] = {
                            "fingerprint": fingerprint,
                            "outbound": error.outbound,
                            "return": None,
                            "partial": True,
                        }
                        st.session_state[pending_mileage_key] = {
                            "fingerprint": fingerprint,
                            "outbound": (
                                None
                                if preserve_manual_outbound
                                else error.outbound
                            ),
                            "return": None,
                        }
                        st.rerun()
                    except Exception as error:  # routing clients vary by provider
                        route_error.error(_safe_route_error(error))
            if submitted:
                if _same_selected_place(start, destination_value):
                    save_error.error(
                        "Starting location and destination must be different."
                    )
                elif start.place_id and not recorded_start.strip():
                    save_error.error(
                        "Enter the starting location text to record in the ledger."
                    )
                elif destination_value.place_id and not recorded_destination.strip():
                    save_error.error(
                        "Enter the destination text to record in the ledger."
                    )
                else:
                    payload = {
                        "trip_date": trip_date,
                        "miles": miles,
                        "return_miles": return_miles,
                        "vehicle": vehicle,
                        "start_location": recorded_start,
                        "destination": recorded_destination,
                        "business_purpose": business_purpose,
                        "notes": notes,
                        "round_trip": round_trip,
                    }
                    context.confirmed_write(
                        "create_mileage_round_trip"
                        if round_trip
                        else "create_mileage_trip",
                        payload,
                        (
                            lambda: _save_round_trip(
                                context.storage,
                                trip_date=trip_date,
                                miles=miles,
                                return_miles=return_miles,
                                vehicle=vehicle,
                                start_location=recorded_start,
                                destination=recorded_destination,
                                business_purpose=business_purpose,
                                notes=notes,
                            )
                        )
                        if round_trip
                        else lambda: context.storage.create_mileage_trip(
                            trip_date=trip_date,
                            miles=miles,
                            vehicle=vehicle,
                            start_location=recorded_start,
                            destination=recorded_destination,
                            business_purpose=business_purpose,
                            notes=notes,
                        ),
                        (
                            "Round trip saved as two mileage entries."
                            if round_trip
                            else "Mileage trip saved."
                        ),
                        on_success=lambda: context.schedule_widget_reset(
                            "reset_add_mileage_form"
                        ),
                        report_error=save_error.error,
                    )

    with tab_log:
        st.subheader("Mileage log")
        c1, c2 = st.columns(2, gap="small")
        start = c1.date_input(
            "From", date(date.today().year, 1, 1), key="mileage_start"
        )
        end = c2.date_input("To", date.today(), key="mileage_end")
        try:
            trips = context.storage.list_mileage_trips(start=start, end=end)
        except StorageError as error:
            context.report_storage_error(error)
            with page_footer.container():
                render_global_footer()
            st.stop()

        trip_frame = mileage_frame(trips)
        metric_trips, metric_miles = st.columns(2, gap="small")
        metric_trips.metric("Trips", len(trips))
        metric_miles.metric(
            "Business miles",
            f"{trip_frame['Miles'].sum():,.1f}" if not trip_frame.empty else "0.0",
        )
        st.download_button(
            "Download filtered mileage CSV",
            trip_frame.to_csv(index=False).encode("utf-8"),
            f"tabula-rasa-mileage-{start}-to-{end}.csv",
            "text/csv",
        )

        trip_ids = trip_frame["ID"].tolist()

        mileage_table_key = (
            f"mileage_log_{context.profile_key}_"
            f"{st.session_state.get('mileage_log_generation', 0)}"
        )

        def select_mileage_trip() -> None:
            selected_rows = st.session_state[mileage_table_key].selection.rows
            if selected_rows:
                st.session_state["edit_mileage_trip_id"] = trip_ids[
                    selected_rows[0]
                ]

        mileage_event = st.dataframe(
            trip_frame,
            hide_index=True,
            width="stretch",
            key=mileage_table_key,
            on_select=select_mileage_trip,
            selection_mode="single-row",
            column_config={
                "Miles": st.column_config.NumberColumn(format="%.1f"),
            },
        )
        if trip_frame.empty:
            st.info("No mileage trips in this period.")
        else:
            selected_rows = mileage_event.selection.rows
            if st.session_state.get("edit_mileage_trip_id") not in trip_ids:
                st.session_state["edit_mileage_trip_id"] = trip_ids[0]

            def mileage_trip_label(trip_id: str) -> str:
                row = trip_frame.loc[trip_frame["ID"] == trip_id].iloc[0]
                return (
                    f"{row['Date']} - {row['Miles']:,.1f} mi - "
                    f"{row['Destination']} - {trip_id[:8]}"
                )

            st.caption("Select a mileage row (or double-click it) to edit it.")
            with st.expander("Edit mileage trip", expanded=bool(selected_rows)):
                edit_id = st.selectbox(
                    "Mileage trip to edit",
                    trip_ids,
                    format_func=mileage_trip_label,
                    key="edit_mileage_trip_id",
                )
                selected = next(trip for trip in trips if trip["id"] == edit_id)
                edit_widget_scope = f"{context.profile_key}_{edit_id}"
                edit_start = address_autocomplete(
                    "Edit starting location",
                    key=f"edit_mileage_trip_start_{edit_widget_scope}",
                    api_key=context.maps_api_key,
                    value=_edit_address_initial_value(
                        selected.get("start_location", ""),
                        context.maps_api_key,
                    ),
                    region_code=context.autocomplete_region_code,
                )
                edit_destination = address_autocomplete(
                    "Edit destination",
                    key=f"edit_mileage_trip_destination_{edit_widget_scope}",
                    api_key=context.maps_api_key,
                    value=_edit_address_initial_value(
                        selected.get("destination", ""),
                        context.maps_api_key,
                    ),
                    region_code=context.autocomplete_region_code,
                )
                edit_route_key = _route_key(context, f"edit_{edit_id}")
                edit_fingerprint = _selection_fingerprint(
                    edit_start, edit_destination
                )
                edit_route_state = st.session_state.get(edit_route_key)
                edit_route_changed = False
                _discard_modified_calculated_mileage_markers(
                    miles_key=f"edit_mileage_trip_miles_{edit_widget_scope}",
                )
                if (
                    edit_route_state
                    and edit_route_state.get("fingerprint") != edit_fingerprint
                ):
                    _clear_unchanged_calculated_mileage(
                        edit_route_state,
                        miles_key=f"edit_mileage_trip_miles_{edit_widget_scope}",
                    )
                    st.session_state.pop(edit_route_key, None)
                    edit_route_state = None
                    edit_route_changed = True
                edit_pending_mileage_key = f"{edit_route_key}__pending_miles"
                _apply_pending_route_mileage(
                    st.session_state.pop(edit_pending_mileage_key, None),
                    fingerprint=edit_fingerprint,
                    round_trip=False,
                    miles_key=f"edit_mileage_trip_miles_{edit_widget_scope}",
                )
                edited_start = _ledger_location_text(
                    edit_start,
                    label="Starting location",
                    key=f"edit_mileage_trip_recorded_start_{edit_widget_scope}",
                    existing_value=selected.get("start_location", ""),
                    always_render=bool(context.maps_api_key),
                )
                edited_destination = _ledger_location_text(
                    edit_destination,
                    label="Destination",
                    key=f"edit_mileage_trip_recorded_destination_{edit_widget_scope}",
                    existing_value=selected.get("destination", ""),
                    always_render=bool(context.maps_api_key),
                )
                edit_address_changed = _address_text_changed(
                    edit_start,
                    edit_destination,
                    selected.get("start_location", ""),
                    selected.get("destination", ""),
                )
                edit_recorded_address_changed = (
                    _recorded_address_changed(
                        edited_start,
                        selected.get("start_location", ""),
                        edit_start,
                    )
                    or _recorded_address_changed(
                        edited_destination,
                        selected.get("destination", ""),
                        edit_destination,
                    )
                )
                calculate_edit_requested = st.button(
                    "Recalculate mileage"
                    if edit_route_state
                    else "Calculate mileage",
                    disabled=not _route_ready(
                        edit_start,
                        edit_destination,
                        context.route_mileage,
                    ),
                    key=f"edit_mileage_trip_calculate_{edit_widget_scope}",
                )
                edit_error = st.empty()
                if _needs_google_maps_attribution(
                    edit_start,
                    edit_destination,
                    edit_route_state,
                    edit_fingerprint,
                ):
                    render_google_maps_attribution()
                if _edit_route_warning_visible(
                    edit_address_changed,
                    edit_route_changed,
                    edit_route_state,
                    edit_fingerprint,
                    recorded_address_changed=edit_recorded_address_changed,
                ):
                    st.warning(
                        "The address changed, so the existing mileage may not "
                        "match the current route. Calculate mileage again to "
                        "refresh it, or review and edit the mileage manually "
                        "before saving."
                    )
                # Address autocomplete can rerun this page before save; a
                # container keeps the rest of the draft synchronized in state.
                with st.container():
                    st.caption("Update this saved mileage row.")
                    c1, c2 = st.columns(2, gap="small")
                    edited_date = c1.date_input(
                        "Edit trip date",
                        date.fromisoformat(selected["trip_date"]),
                        key=f"edit_mileage_trip_date_{edit_widget_scope}",
                    )
                    edited_miles = c2.number_input(
                        "Edit business miles",
                        min_value=0.1,
                        step=0.1,
                        value=float(selected["miles"]),
                        format="%.1f",
                        key=f"edit_mileage_trip_miles_{edit_widget_scope}",
                    )
                    edited_vehicle = st.text_input(
                        "Edit vehicle",
                        value=selected.get("vehicle", ""),
                        key=f"edit_mileage_trip_vehicle_{edit_widget_scope}",
                    )
                    edited_purpose = st.text_input(
                        "Edit business purpose",
                        value=selected.get("business_purpose", ""),
                        key=f"edit_mileage_trip_purpose_{edit_widget_scope}",
                    )
                    edited_notes = st.text_area(
                        "Edit notes",
                        value=selected.get("notes", ""),
                        key=f"edit_mileage_trip_notes_{edit_widget_scope}",
                    )
                    st.warning(
                        "Deleting this mileage trip is permanent and cannot be undone."
                    )
                    confirm_delete = st.checkbox(
                        "I understand this mileage trip will be permanently deleted",
                        key=f"edit_mileage_trip_confirm_delete_{edit_widget_scope}",
                    )
                    save_column, delete_column = st.columns(2, gap="small")
                    save_requested = save_column.button(
                        "Save mileage changes",
                        type="primary",
                        width="stretch",
                        key=f"edit_mileage_trip_save_{edit_widget_scope}",
                    )
                    delete_requested = delete_column.button(
                        "Permanently delete mileage trip",
                        icon=":material/delete_forever:",
                        width="stretch",
                        key=f"edit_mileage_trip_delete_{edit_widget_scope}",
                    )
                    if (
                        calculate_edit_requested
                        and context.route_mileage is not None
                    ):
                        with st.spinner("Calculating mileage…"):
                            try:
                                outbound, _ = _calculate_routes(
                                    edit_start,
                                    edit_destination,
                                    context.route_mileage,
                                    round_trip=False,
                                )
                                st.session_state[edit_route_key] = {
                                    "fingerprint": edit_fingerprint,
                                    "outbound": outbound,
                                }
                                st.session_state[edit_pending_mileage_key] = {
                                    "fingerprint": edit_fingerprint,
                                    "outbound": outbound,
                                }
                                st.rerun()
                            except Exception as error:
                                edit_error.error(_safe_route_error(error))
                    if save_requested:
                        if _same_selected_place(edit_start, edit_destination):
                            edit_error.error(
                                "Starting location and destination must be different."
                            )
                        else:
                            payload = {
                                "id": edit_id,
                                "trip_date": edited_date,
                                "miles": edited_miles,
                                "vehicle": edited_vehicle,
                                "start_location": edited_start,
                                "destination": edited_destination,
                                "business_purpose": edited_purpose,
                                "notes": edited_notes,
                            }
                            context.confirmed_write(
                                "edit_mileage_trip",
                                payload,
                                lambda: context.storage.edit_mileage_trip(
                                    edit_id,
                                    trip_date=edited_date,
                                    miles=edited_miles,
                                    vehicle=edited_vehicle,
                                    start_location=edited_start,
                                    destination=edited_destination,
                                    business_purpose=edited_purpose,
                                    notes=edited_notes,
                                ),
                                "Mileage trip updated.",
                                report_error=edit_error.error,
                            )
                    if delete_requested:
                        if not confirm_delete:
                            edit_error.error(
                                "Confirm that you understand deletion is permanent."
                            )
                        else:
                            context.confirmed_write(
                                "delete_mileage_trip",
                                {"id": edit_id},
                                lambda: context.storage.delete_mileage_trip(edit_id),
                                "Mileage trip deleted.",
                                report_error=edit_error.error,
                            )
